// Helper function: get all announcements as an array sorted by date (newest first)
export function getAllAnnouncements() {
  return Object.entries(announcements).map(([id, data]) => ({ slug: id, ...data }));
}

// Helper function: get related announcements (excluding current)
export function getRelatedAnnouncements(currentId, limit = 2) {
  return getAllAnnouncements()
    .filter((a) => a.slug !== currentId)
    .slice(0, limit);
}
