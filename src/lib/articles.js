// Helper function: get all articles as an array sorted by date (newest first)
export function getAllArticles() {
  return Object.entries(articles)
    .map(([id, data]) => ({ id, ...data }))
    .sort((a, b) => new Date(b.dateISO) - new Date(a.dateISO));
}

// Helper function: get related articles (excluding current)
export function getRelatedArticles(currentId, limit = 3) {
  return getAllArticles()
    .filter((a) => a.id !== currentId)
    .slice(0, limit);
}

// Helper function: get unique categories
export function getCategories() {
  const cats = new Set(getAllArticles().map((a) => a.category));
  return ["Semua", ...Array.from(cats)];
}
